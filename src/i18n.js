// Looks up text by key; unknown languages and missing keys fall back to English, then to the key.
function t(lang, key, params) {
  const table = MESSAGES[lang] || MESSAGES.en;
  let s = Object.prototype.hasOwnProperty.call(table, key) ? table[key]
    : (Object.prototype.hasOwnProperty.call(MESSAGES.en, key) ? MESSAGES.en[key] : key);
  if (params) {
    for (const k of Object.keys(params)) s = s.split("{" + k + "}").join(String(params[k]));
  }
  return s;
}

module.exports = { MESSAGES, t };
